# if - else로도 예외 처리를 할 수 있지만, 예외의 조건을 예측하기 힘들어서 Try-Except 구문을 만들었음
입력 = input("정수 입력: ")

try: 
    # 예외가 발생할 수 있는 코드
    숫자입력 = int(입력) 
    print(f"원의 반지름: {숫자입력}")
    print(f"원의 둘레: {2 * 3.14 * 숫자입력}")
    print(f"원의 넓이: {3.14 * 숫자입력 * 숫자입력}")
except:
    # 예외시 실행할 코드
    print("정수를 입력하지 않았습니다") # 출력 후 프로그램 종료
    
# 입력이 부동 소수점일때
입력2 = input("숫자 입력: ") 

try:
    # 예외가 발생할 수 있는 코드
    숫자입력2 = float(입력2) 
    print(f"원의 반지름: {숫자입력2}")
    print(f"원의 둘레: {2 * 3.14 * 숫자입력2}")
    print(f"원의 넓이: {3.14 * 숫자입력2 * 숫자입력2}")
except:
    print("숫자를 입력해주세요")
    
